// Tasarım denenmek istenmezse false yaparak bütün spotlight satırları kapatılabilir.
export const SPOTLIGHT_CAROUSELS_ENABLED = true;

export interface SpotlightTheme {
  accent: string;
  accentContrast: "#ffffff" | "#090909";
  typography: SpotlightTypography;
  backgroundPosition?: string;
}

interface SpotlightBaseDefinition {
  id: string;
  title: string;
  eyebrow: string;
  description: string;
  placements: SpotlightPlacement[];
  theme: SpotlightTheme;
}

export type SpotlightDefinition = SpotlightBaseDefinition & (
  | {
      source: "collection";
      sourceIds: number[];
      order?: "release" | "source";
    }
  | {
      source: "person";
      sourceId: number;
      backgroundMovieId: number;
    }
);

function theme(
  accent: string,
  typography: SpotlightTypography,
  accentContrast: SpotlightTheme["accentContrast"] = "#090909",
  backgroundPosition = "center 30%",
): SpotlightTheme {
  return { accent, accentContrast, typography, backgroundPosition };
}

